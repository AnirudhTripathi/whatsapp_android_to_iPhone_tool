# Fix-up pass after watoi, LID-aware variant of MdShahnawazSheikh/.../scripts/post.sh (GPL-3.0).
# Makes imported rows look like rows WhatsApp iOS 26.44 writes itself (values observed on a real
# iPhone backup, November 2026), WITHOUT touching group membership that WhatsApp already synced.
# usage: post_lid.sh <ChatStorage.sqlite> <msgstore_lid.db> <baseline_session_pk> <baseline_message_pk> <baseline_member_pk>
set -euo pipefail
DB="$1"; SHIM="$2"; S="$3"; M="$4"; G="$5"
sqlite3 "$DB" <<SQL
ATTACH '$SHIM' AS a;
BEGIN;
-- sessions created by watoi
UPDATE ZWACHATSESSION SET ZSESSIONTYPE=1, ZSPOTLIGHTSTATUS=1,  ZFLAGS=256 WHERE Z_PK>$S AND ZGROUPINFO IS NOT NULL;
UPDATE ZWACHATSESSION SET ZSESSIONTYPE=0, ZSPOTLIGHTSTATUS=-5, ZFLAGS=272 WHERE Z_PK>$S AND ZGROUPINFO IS NULL;
UPDATE ZWACHATSESSION SET ZCONTACTIDENTIFIER=(SELECT phone FROM a.canon_phone cp WHERE cp.canon=ZWACHATSESSION.ZCONTACTJID)
 WHERE Z_PK>$S AND ZGROUPINFO IS NULL AND ZCONTACTJID LIKE '%@lid' AND ZCONTACTIDENTIFIER IS NULL;
UPDATE ZWACHATSESSION SET ZPARTNERNAME='+'||substr(ZCONTACTIDENTIFIER,1,instr(ZCONTACTIDENTIFIER,'@')-1)
 WHERE Z_PK>$S AND ZGROUPINFO IS NULL AND ZCONTACTIDENTIFIER IS NOT NULL;
UPDATE ZWACHATSESSION SET ZPARTNERNAME='+'||substr(ZCONTACTJID,1,instr(ZCONTACTJID,'@')-1)
 WHERE Z_PK>$S AND ZGROUPINFO IS NULL AND ZCONTACTJID LIKE '%@s.whatsapp.net';
UPDATE ZWACHATSESSION SET ZARCHIVED=COALESCE(ZARCHIVED,0), ZHIDDEN=COALESCE(ZHIDDEN,0), ZREMOVED=COALESCE(ZREMOVED,0),
       ZUNREADCOUNT=COALESCE(ZUNREADCOUNT,0), ZCONTACTABID=COALESCE(ZCONTACTABID,0),
       ZIDENTITYVERIFICATIONSTATE=COALESCE(ZIDENTITYVERIFICATIONSTATE,0)
 WHERE Z_PK>$S;

-- imported messages: same defaults as native rows
UPDATE ZWAMESSAGE SET ZMESSAGESTATUS=8, ZDATAITEMVERSION=3, ZSPOTLIGHTSTATUS=-32768, ZMESSAGEERRORSTATUS=0,
       ZFLAGS=CASE ZISFROMME WHEN 1 THEN 16777280 ELSE 16777216 END,
       ZSENTDATE=ZMESSAGEDATE
 WHERE Z_PK>$M;

-- last-message pointers for sessions that have none (watoi leaves them NULL)
UPDATE ZWACHATSESSION SET ZLASTMESSAGE=(SELECT Z_PK FROM ZWAMESSAGE m WHERE m.ZCHATSESSION=ZWACHATSESSION.Z_PK ORDER BY m.ZSORT DESC LIMIT 1)
 WHERE ZLASTMESSAGE IS NULL AND EXISTS(SELECT 1 FROM ZWAMESSAGE m WHERE m.ZCHATSESSION=ZWACHATSESSION.Z_PK);
UPDATE ZWACHATSESSION SET ZLASTMESSAGEDATE=(SELECT ZMESSAGEDATE FROM ZWAMESSAGE WHERE Z_PK=ZWACHATSESSION.ZLASTMESSAGE)
 WHERE ZLASTMESSAGEDATE IS NULL AND ZLASTMESSAGE IS NOT NULL;

-- members watoi had to create (people no longer in the group): inactive, readable fallback name
UPDATE ZWAGROUPMEMBER SET ZISACTIVE=0,
       ZCONTACTIDENTIFIER=COALESCE(ZCONTACTIDENTIFIER,(SELECT phone FROM a.canon_phone cp WHERE cp.canon=ZWAGROUPMEMBER.ZMEMBERJID)),
       ZCONTACTNAME=(SELECT '+'||substr(phone,1,instr(phone,'@')-1) FROM a.canon_phone cp WHERE cp.canon=ZWAGROUPMEMBER.ZMEMBERJID)
 WHERE Z_PK>$G;

UPDATE ZWAMESSAGE SET ZSTARRED=1
 WHERE Z_PK>$M AND EXISTS(SELECT 1 FROM a.starred_keys sk JOIN ZWACHATSESSION s ON s.Z_PK=ZWAMESSAGE.ZCHATSESSION
                          WHERE sk.key_id=ZWAMESSAGE.ZSTANZAID AND sk.jid=s.ZCONTACTJID);
COMMIT;
DETACH a;
VACUUM;
SQL
